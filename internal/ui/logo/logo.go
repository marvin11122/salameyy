// letterform represents a letterform. It can be stretched horizontally by
// a given amount via the boolean argument.
type letterform func(bool) string

const diag = `╱`

// Opts are the options for rendering the title art.
type Opts struct {
	FieldColor   color.Color // diagonal lines
	TitleColorA  color.Color // left gradient ramp point
	TitleColorB  color.Color // right gradient ramp point
	CharmColor   color.Color // Meta label text color
	VersionColor color.Color // Version text color
	Width        int         // width of the rendered logo, used for truncation
}

// Render renders the SALAMEY logo. Set compact to true for the sidebar.
func Render(s *styles.Styles, version string, compact bool, o Opts) string {
	const metaLabel = " " + brand.HeaderMark

	fg := func(c color.Color, s string) string {
		return lipgloss.NewStyle().Foreground(c).Render(s)
	}

	title := renderBanner(s, o.TitleColorA, o.TitleColorB)
	titleWidth := lipgloss.Width(title)
	b := new(strings.Builder)

	metaRowGap := 1
	maxVersionWidth := titleWidth - lipgloss.Width(metaLabel) - metaRowGap
	version = ansi.Truncate(version, maxVersionWidth, "…")
	gap := max(0, titleWidth-lipgloss.Width(metaLabel)-lipgloss.Width(version))
	metaRow := fg(o.CharmColor, metaLabel) + strings.Repeat(" ", gap) + fg(o.VersionColor, version)
	fmt.Fprintln(b, metaRow)
	fmt.Fprint(b, title)
	logoText := strings.TrimSpace(b.String())

	if compact {
		field := fg(o.FieldColor, strings.Repeat(diag, titleWidth))
		return strings.Join([]string{field, logoText, field, ""}, "\n")
	}

	fieldHeight := lipgloss.Height(logoText)
	const leftWidth = 6
	leftFieldRow := fg(o.FieldColor, strings.Repeat(diag, leftWidth))
	leftField := new(strings.Builder)
	for range fieldHeight {
		fmt.Fprintln(leftField, leftFieldRow)
	}

	// Right field.
	rightWidth := max(15, o.Width-titleWidth-leftWidth-2) // 2 for the gap.
	const stepDownAt = 0
	rightField := new(strings.Builder)
	for i := range fieldHeight {
		width := rightWidth
		if i >= stepDownAt {
			width = rightWidth - (i - stepDownAt)
		}
		fmt.Fprint(rightField, fg(o.FieldColor, strings.Repeat(diag, width)), "\n")
	}

	const hGap = " "
	logo := lipgloss.JoinHorizontal(lipgloss.Top, leftField.String(), hGap, logoText, hGap, rightField.String())
	if o.Width > 0 {
		lines := strings.Split(logo, "\n")
		for i, line := range lines {
			lines[i] = ansi.Truncate(line, o.Width, "")
		}
		logo = strings.Join(lines, "\n")
	}
	return logo
}

func renderBanner(t *styles.Styles, colorA, colorB color.Color) string {
	lines := []string{
		"███████  █████  ██       █████  ███    ███ ███████ ██    ██",
		"██      ██   ██ ██      ██   ██ ████  ████ ██       ██  ██",
		"███████ ███████ ██      ███████ ██ ████ ██ █████     ████",
		"     ██ ██   ██ ██      ██   ██ ██  ██  ██ ██         ██",
		"███████ ██   ██ ███████ ██   ██ ██      ██ ███████    ██",
	}

	rendered := make([]string, 0, len(lines))
	for _, line := range lines {
		rendered = append(rendered, styles.ApplyForegroundGrad(t, line, colorA, colorB))
	}
	return strings.Join(rendered, "\n")
}

// SmallRender renders a smaller version of the SALAMEY logo.
func SmallRender(t *styles.Styles, width int) string {
	title := t.Base.Foreground(t.Secondary).Render(brand.HeaderMark)
	title = fmt.Sprintf("%s %s", title, styles.ApplyBoldForegroundGrad(t, brand.Wordmark, t.Secondary, t.Primary))
	remainingWidth := width - lipgloss.Width(title) - 1
	if remainingWidth > 0 {
		lines := strings.Repeat("╱", remainingWidth)
		title = fmt.Sprintf("%s %s", title, t.Base.Foreground(t.Primary).Render(lines))
	}
	return title
}

// renderWord renders letterforms to form a word. stretchIndex is the index of
// the letter to stretch, or -1 if no letter should be stretched.
func renderWord(spacing int, stretchIndex int, letterforms ...letterform) string {
	if spacing < 0 {
		spacing = 0
	}

	renderedLetterforms := make([]string, len(letterforms))

	// pick one letter randomly to stretch
	for i, letter := range letterforms {
		renderedLetterforms[i] = letter(i == stretchIndex)
	}

	if spacing > 0 {
		// Add spaces between the letters and render.
		renderedLetterforms = slice.Intersperse(renderedLetterforms, strings.Repeat(" ", spacing))
	}
	return strings.TrimSpace(
		lipgloss.JoinHorizontal(lipgloss.Top, renderedLetterforms...),
	)
}

// letterC renders the letter C in a stylized way. It takes an integer that
// determines how many cells to stretch the letter. If the stretch is less than
// 1, it defaults to no stretching.
func letterC(stretch bool) string {
	// Here's what we're making:
	//
	// ▄▀▀▀▀
	// █
	//	▀▀▀▀

	left := heredoc.Doc(`
		▄
		█
	`)
	right := heredoc.Doc(`
		▀

		▀
	`)
	return joinLetterform(
		left,
		stretchLetterformPart(right, letterformProps{
			stretch:    stretch,
			width:      4,
			minStretch: 7,
			maxStretch: 12,
		}),
	)
}

